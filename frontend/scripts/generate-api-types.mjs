// Generates src/shared/api/schema.d.ts from openapi.json (02-arquitectura.md §7).
// A binary field (OpenAPI 3.1 contentMediaType, or 3.0 format binary) becomes Blob, so an upload sends File objects with no type assertion.
import { writeFileSync } from "node:fs";

import openapiTS, { astToString } from "openapi-typescript";
import ts from "typescript";

const BLOB = ts.factory.createTypeReferenceNode(ts.factory.createIdentifier("Blob"));

const ast = await openapiTS(new URL("../openapi.json", import.meta.url), {
  transform(schemaObject) {
    const binary =
      schemaObject.format === "binary" ||
      schemaObject.contentMediaType === "application/octet-stream";
    return binary ? BLOB : undefined;
  },
});

const header = "// Generated by scripts/generate-api-types.mjs from openapi.json. Do not edit.\n\n";
writeFileSync(new URL("../src/shared/api/schema.d.ts", import.meta.url), header + astToString(ast));
console.log("src/shared/api/schema.d.ts generated.");
